"""Static types for the parts of Portfolio Performance's Java API this package uses.

JPype hands back untyped proxies. Rather than let them flow through as `Any`, each Java class
is looked up once here, cast to a `Protocol` that lists the members we call, and everything
downstream is checked against those protocols. The protocols describe the PP 0.8x/0.9x model;
if a call is not listed here, add it here first.

Notes on JPype's mapping (with `convertStrings=False`, as `bridge.start_jvm` sets it):

* Java strings arrive as `java.lang.String` objects, not `str`: typed `JString`, read with `str()`.
* Java `null` arrives as `None`; nullable getters are typed `X | None`.
* Java primitives arrive as subclasses of `int`/`float`/`bool`, so they are typed as those.
* A static Java method named `from` is exposed as `from_`.
"""

from __future__ import annotations

